"""Generates the Material 3 color scheme used by the app from a single seed color.

Writes Compose colors (ui/.../Color.kt) and the XML colors the window/splash theme needs
(app/.../values/colors.xml and values-night/colors.xml), and fails if a text/background pair
drops below WCAG AA contrast.

    uv run --with materialyoucolor python tools/theme/generate_color_scheme.py [--seed E58325]

The default seed is Mealie's brand orange. SchemeVibrant keeps it warm instead of the muddy brown
that SchemeTonalSpot produces for orange.
"""
import argparse
import pathlib
import sys

from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_vibrant import SchemeVibrant

ROOT = pathlib.Path(__file__).resolve().parents[2]

# Compose role name -> MaterialDynamicColors attribute (identical here, listed for ordering).
ROLES = [
    "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
    "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
    "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
    "background", "onBackground",
    "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceTint",
    "inverseSurface", "inverseOnSurface",
    "error", "onError", "errorContainer", "onErrorContainer",
    "outline", "outlineVariant", "scrim",
    "surfaceBright", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
    "surfaceContainerLow", "surfaceContainerLowest", "surfaceDim",
]

# (foreground, background) pairs that must stay readable.
CONTRAST_PAIRS = [
    ("onPrimary", "primary"), ("onPrimaryContainer", "primaryContainer"),
    ("onSecondary", "secondary"), ("onSecondaryContainer", "secondaryContainer"),
    ("onTertiary", "tertiary"), ("onTertiaryContainer", "tertiaryContainer"),
    ("onError", "error"), ("onErrorContainer", "errorContainer"),
    ("onBackground", "background"), ("onSurface", "surface"),
    ("onSurfaceVariant", "surfaceVariant"), ("inverseOnSurface", "inverseSurface"),
    ("onSurface", "surfaceContainerHighest"), ("primary", "surface"),
]


def build(seed: int, dark: bool) -> dict:
    scheme = SchemeVibrant(Hct.from_int(0xFF000000 | seed), dark, 0.0)
    return {role: getattr(M, role).get_argb(scheme) & 0xFFFFFFFF for role in ROLES}


def luminance(argb: int) -> float:
    def channel(c: int) -> float:
        v = c / 255
        return v / 12.92 if v <= 0.03928 else ((v + 0.055) / 1.055) ** 2.4
    r, g, b = (argb >> 16) & 255, (argb >> 8) & 255, argb & 255
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: int, b: int) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def snake(role: str) -> str:
    return "".join("_" + c.lower() if c.isupper() else c for c in role)


def kotlin_scheme(name: str, factory: str, colors: dict) -> str:
    lines = [f"internal val {name} = {factory}("]
    lines += [f"    {role} = Color(0x{colors[role]:08X})," for role in ROLES]
    lines.append(")")
    return "\n".join(lines)


def xml_colors(colors: dict) -> str:
    body = "\n".join(
        f'    <color name="md_theme_{snake(role)}">#{colors[role] & 0xFFFFFF:06X}</color>' for role in ROLES
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/theme/generate_color_scheme.py, do not edit. -->\n"
        f"<resources>\n{body}\n</resources>\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", default="E58325", help="seed color, RRGGBB hex")
    seed = int(parser.parse_args().seed, 16)

    light, dark = build(seed, False), build(seed, True)

    failures = []
    for label, colors in (("light", light), ("dark", dark)):
        for fg, bg in CONTRAST_PAIRS:
            ratio = contrast(colors[fg], colors[bg])
            # primary on surface is used for text buttons and links, so it is held to AA as well.
            if ratio < 4.5:
                failures.append(f"{label}: {fg} on {bg} = {ratio:.2f}")
    if failures:
        print("Contrast check failed:\n  " + "\n  ".join(failures), file=sys.stderr)
        return 1

    kotlin = (
        "package gq.kirmanak.mealient.ui\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        "// Generated by tools/theme/generate_color_scheme.py (seed #%06X), do not edit.\n\n" % seed
        + kotlin_scheme("LightColorScheme", "lightColorScheme", light) + "\n\n"
        + kotlin_scheme("DarkColorScheme", "darkColorScheme", dark) + "\n"
    )
    (ROOT / "ui/src/main/kotlin/gq/kirmanak/mealient/ui/Color.kt").write_text(kotlin)

    res = ROOT / "app/src/main/res"
    (res / "values").mkdir(parents=True, exist_ok=True)
    (res / "values-night").mkdir(parents=True, exist_ok=True)
    (res / "values/colors.xml").write_text(xml_colors(light))
    (res / "values-night/colors.xml").write_text(xml_colors(dark))
    print(f"Generated scheme from #{seed:06X}: primary light #{light['primary'] & 0xFFFFFF:06X}, "
          f"dark #{dark['primary'] & 0xFFFFFF:06X}; all {len(CONTRAST_PAIRS) * 2} contrast checks >= 4.5")
    return 0


if __name__ == "__main__":
    sys.exit(main())
